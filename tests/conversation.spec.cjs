/* Run against `python -m http.server 8765`; requires Playwright + Chromium. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const sandbox = {window:{}};
vm.runInNewContext(fs.readFileSync('js/conversation-data.js','utf8'),sandbox);
const units = sandbox.window.CONVERSATION_DATA.units;
const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:8765';
const key = 'gken_conversation_m2_01_v1';
const shots = process.env.TEST_SCREENSHOT_DIR || '/tmp/gkentei-conversation-screenshots';
fs.mkdirSync(shots,{recursive:true});
(async()=>{
  const browser = await chromium.launch({headless:true, executablePath:process.env.TEST_CHROMIUM_PATH || undefined, args:['--no-sandbox', '--disable-dev-shm-usage']});
  const ctx = await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,permissions:['clipboard-read','clipboard-write']});
  const page = await ctx.newPage();
  const errors=[];
  page.on('pageerror', e=>errors.push(e.message));
  const requests=[];
  page.on('request',r=>requests.push(r.url()));
  const goto=async(path)=>{await page.goto(base+path);};
  const click=async(action)=>page.locator(`[data-action="${action}"]`).click();
  const store=()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
  const noOverflow=async()=>assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'No mobile horizontal overflow');
  await goto('/index.html');
  await page.waitForFunction(()=>document.getElementById('load-status').hidden);
  // Seed normal-drill progress and ensure conversation never changes it.
  const normal = JSON.stringify({history:{'M2-01-1':{a:3,c:2,last:true}},sessions:[],days:{},reads:{'M2-01':120}});
  await page.evaluate(v=>localStorage.setItem('gken_store_v1',v),normal);
  await page.getByRole('link',{name:/会話で学習/}).click();
  await click('start');
  await noOverflow();
  await page.screenshot({path:shots+'/conversation-read.png',fullPage:true});
  await click('more');
  assert.match(await page.locator('#cv-help').innerText(),/広さ30㎡/);
  await click('example');
  assert.match(await page.locator('#cv-help').innerText(),/メール/);
  await page.reload(); await click('resume');
  assert.equal((await store()).stage,'read');
  await click('quiz');
  await page.reload(); await click('resume');
  assert.equal(await page.locator('.cv-choice').count(),4);
  await noOverflow();
  await page.screenshot({path:shots+'/conversation-quiz.png',fullPage:true});
  await page.locator('[data-choice="0"]').click(); // deliberately incorrect
  assert.match(await page.locator('.cv-result').innerText(),/不正解/);
  assert.equal((await store()).answers.supervised.selected,0);
  await click('again');
  assert.match(await page.locator('#cv-help').innerText(),/答え付き/);
  await page.screenshot({path:shots+'/conversation-review.png',fullPage:true});
  const beforeCopy=requests.length;
  await click('ai');
  await page.getByText('✓ 質問文をコピーしました。次にChatGPTを開いて貼り付けてください。').waitFor();
  const prompt = await page.locator('#cv-prompt').inputValue();
  for (const text of ['M2-01',units[0].topic,units[0].question,'私が選んだ回答：①','正解：②',units[0].explanation,'この部分がよく理解できないので、分かりやすく説明してください。']) assert.ok(prompt.includes(text),text);
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),prompt);
  assert.equal(requests.slice(beforeCopy).some(url=>!url.startsWith(base)),false,'AI button makes no external requests');
  assert.equal(await page.getByRole('link',{name:/ChatGPTを開く/}).getAttribute('href'),'https://chatgpt.com/');
  await page.reload(); await click('resume');
  assert.match(await page.locator('.cv-result').innerText(),/不正解/);
  assert.equal((await store()).index,0);
  await click('next');
  for (let i=1;i<units.length;i++) {
    assert.equal((await store()).index,i);
    await noOverflow();
    await click('quiz');
    await page.locator(`[data-choice="${units[i].answer}"]`).click();
    assert.match(await page.locator('.cv-result').innerText(),/正解です/);
    await click('example');
    assert.ok((await page.locator('#cv-help').innerText()).length>40);
    await click('next');
  }
  assert.equal((await store()).stage,'done');
  assert.equal(Object.keys((await store()).answers).length,9);
  assert.match(await page.locator('#cv-percent').innerText(),/100%/);
  assert.match(await page.locator('.cv-score').innerText(),/8/);
  assert.equal(await page.evaluate(()=>localStorage.getItem('gken_store_v1')),normal);
  await page.reload(); await click('resume');
  await page.screenshot({path:shots+'/conversation-complete.png',fullPage:true});
  await page.emulateMedia({colorScheme:'dark'}); await noOverflow();
  await page.screenshot({path:shots+'/conversation-dark.png',fullPage:true});
  // Small phone and large font.
  await page.setViewportSize({width:320,height:640});
  await page.evaluate(()=>document.documentElement.style.fontSize='20px');
  await noOverflow();
  // Regressions: source textbook, ordinary drill, passport entry isolation.
  await goto('/index.html');
  await page.waitForFunction(()=>document.getElementById('load-status').hidden);
  await page.locator('.lesson').filter({has:page.locator('.lesson__id',{hasText:'M2-01'})}).click();
  assert.equal(await page.locator('#btn-conversation-lesson').isVisible(),true);
  await page.locator('#btn-read').click();
  assert.match(await page.locator('#read-body').innerText(),/カーネルトリック/);
  await page.locator('#btn-read-drill').click();
  await page.locator('#q-options button').first().click();
  assert.equal(await page.locator('#q-feedback').isVisible(),true);
  await goto('/index.html?exam=passport');
  await page.waitForFunction(()=>document.getElementById('load-status').hidden);
  assert.equal(await page.locator('.conversation-entry').isVisible(),false);
  await page.locator('.lesson').first().click();
  assert.equal(await page.locator('#btn-conversation-lesson').isVisible(),false);
  // Offline from precache without a previous visit to conversation resources.
  const offlineCtx=await browser.newContext({viewport:{width:390,height:844},isMobile:true});
  const offlinePage=await offlineCtx.newPage();
  await offlinePage.goto(base+'/index.html');
  await offlinePage.evaluate(async()=>{await navigator.serviceWorker.ready;});
  await offlinePage.waitForFunction(()=>!!navigator.serviceWorker.controller);
  await offlineCtx.setOffline(true);
  await offlinePage.goto(base+'/conversation.html');
  await offlinePage.locator('[data-action="start"]').click();
  assert.equal(await offlinePage.locator('.cv-title').innerText(),units[0].title);
  assert.equal(await offlinePage.evaluate(()=>getComputedStyle(document.querySelector('.cv-card')).borderRadius),'18px');
  await offlinePage.locator('[data-action="quiz"]').click();
  await offlinePage.locator('[data-choice="1"]').click();
  await offlinePage.reload();
  await offlinePage.locator('[data-action="resume"]').click();
  assert.equal(await offlinePage.locator('.cv-check-title').innerText(),'確認タイム');
  await offlineCtx.close();
  // Invalid saved JSON must not crash or touch ordinary records.
  await goto('/conversation.html');
  await page.evaluate(k=>localStorage.setItem(k,'{broken'),key);
  await page.reload();
  assert.equal(await page.locator('[data-action="start"]').isVisible(),true);
  assert.match(await page.locator('#cv-storage').innerText(),/読み込めません/);
  // Explicit clipboard denial + legacy copy failure retains selectable prompt.
  await click('start'); await click('quiz'); await page.locator('[data-choice="1"]').click();
  await page.evaluate(()=>{
    Object.defineProperty(navigator,'clipboard',{value:{writeText:()=>Promise.reject(new Error('denied'))},configurable:true});
    document.execCommand=()=>false;
  });
  await click('ai');
  await page.getByText(/自動コピーできませんでした/).waitFor();
  assert.ok((await page.locator('#cv-prompt').inputValue()).includes('M2-01'));
  // Storage unavailable: user sees truthful warning, can still answer.
  const blocked=await browser.newContext();
  await blocked.addInitScript(()=>{Storage.prototype.setItem=function(){throw new Error('quota');};});
  const bp=await blocked.newPage();
  await bp.goto(base+'/conversation.html');
  await bp.locator('[data-action="start"]').click();
  assert.match(await bp.locator('#cv-storage').innerText(),/保存できません/);
  await bp.locator('[data-action="quiz"]').click(); await bp.locator('[data-choice="1"]').click();
  assert.equal(await bp.locator('.cv-check-title').innerText(),'確認タイム');
  await blocked.close();
  assert.deepEqual(errors,[]);
  console.log('PASS: 9-unit flow; wrong/correct answers; mobile/large-font/dark layout; resume in each stage; clipboard + denied fallback; no AI requests; existing drill/passport; offline cold precache + resume; corrupt/quota storage.');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
